/**
 * Regenerates tests/dashera-session-tools.snapshot.ts from the Dashera repo:
 * every connector tool whose input schema has a `session` property, with its
 * access (read or write) and that property's description. The plugin can't
 * see MCP schemas at run time, so tests/sessiontools.test.ts holds
 * SESSION_WRITE_TOOLS and NEVER_FILL to this snapshot.
 *
 * Run it whenever Dashera adds, renames or drops a tool that takes `session`,
 * with the Dashera agent-cli's own tsx (it imports tools.ts):
 *
 *   cd <dashera>/lib/agent-cli
 *   ./node_modules/.bin/tsx <plugin>/scripts/sync-session-tools.ts \
 *     "$PWD/src/tools.ts" <plugin>/tests/dashera-session-tools.snapshot.ts
 *
 * Reads only tools.ts; writes only the snapshot file named.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname } from 'node:path'

type Tool = { name: string; access: string }
type Schema = { properties?: Record<string, { description?: string }> }
type Module = {
  toolsForMode: (...a: unknown[]) => Tool[]
  toolInputSchema: (t: Tool) => Schema
}

async function main(toolsPath: string, outPath: string) {
  const m = (await import(toolsPath)) as Module
  // Every tool a read-write agent account can be offered: full profile, all lists.
  const tools = m.toolsForMode('read_write', undefined, true, 'full', null, 'all', { brief: false })
  if (tools.length === 0) throw new Error('no tools listed: has toolsForMode changed?')

  const rows = tools
    .map(t => ({ t, p: m.toolInputSchema(t)?.properties?.session }))
    .filter(x => x.p)
    .map(({ t, p }) => ({
      name: t.name,
      access: t.access === 'read' ? 'read' : 'write',
      description: p!.description ?? '',
    }))
    .sort((a, b) => a.name.localeCompare(b.name))

  let commit = 'unknown'
  try {
    commit = execFileSync('git', ['-C', dirname(toolsPath), 'rev-parse', '--short', 'HEAD'], {
      encoding: 'utf8',
    }).trim()
  } catch {
    // Not a git checkout: the snapshot says unknown.
  }

  const body = `// Generated by scripts/sync-session-tools.ts from Dashera ${commit}
// (lib/agent-cli/src/tools.ts). Do not edit: regenerate it whenever Dashera
// adds, renames or drops a tool that takes \`session\`.

export type SessionTool = { name: string; access: 'read' | 'write'; description: string }

export const DASHERA_COMMIT = ${JSON.stringify(commit)}

export const DASHERA_SESSION_TOOLS: readonly SessionTool[] = [
${rows.map(r => `  ${JSON.stringify(r)},`).join('\n')}
]
`
  writeFileSync(outPath, body)
  const writes = rows.filter(r => r.access === 'write').length
  console.log(`${rows.length} tools with session (${writes} writes) from ${commit} -> ${outPath}`)
}

const [toolsPath, outPath] = process.argv.slice(2)
if (!toolsPath || !outPath) {
  console.error('usage: sync-session-tools.ts <dashera>/lib/agent-cli/src/tools.ts <out.ts>')
  process.exit(2)
}
main(toolsPath, outPath).catch(err => {
  console.error(err)
  process.exit(1)
})
